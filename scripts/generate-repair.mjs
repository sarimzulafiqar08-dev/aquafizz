// Builds supabase/repair/reset_to_app_schema.sql:  npm run db:repair-sql
// For a project where a different schema was created first. It keeps auth users and
// their admin roles, replaces the app tables with the real migration, and seeds products.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8').replace(/\r\n?/g, '\n')
const migration = read('supabase/migrations/20261019000000_ecommerce.sql')
const seed = read('supabase/seed.sql')

// Statements touching Supabase-owned storage tables run inside guarded blocks.
const guard = (stmt) =>
  `do $guard$
begin
  execute $stmt$${stmt.trim().replace(/;$/, '')}$stmt$;
exception when insufficient_privilege or duplicate_object then
  raise notice 'Skipped (not permitted or already exists): %', left($stmt$${stmt.trim().split('\n')[0]}$stmt$, 80);
end $guard$;`
const appSchema = migration.replace(
  /^(create policy "[^"]+" on storage\.objects[\s\S]*?;|insert into storage\.buckets[\s\S]*?;)(?=\r?$)/gm,
  (stmt) => guard(stmt),
)

const sql = `-- ⚠️ ONE-TIME REPAIR — run in Supabase SQL Editor as a single script.
-- Generated by scripts/generate-repair.mjs. Do NOT run on a project with real orders:
-- it drops and recreates products, orders, order_items, store_settings, wishlist_items and profiles.
-- Auth users are kept, and anyone who was 'admin' in the old profiles table stays admin.

begin;

-- 1. Remember existing profiles (names + roles) before dropping the old table.
create temp table _old_profiles on commit drop as
  select id, coalesce(email, '') as email, coalesce(full_name, '') as full_name, role::text as role
  from public.profiles;

-- 2. Remove the old schema.
drop table if exists public.order_items, public.orders, public.products,
  public.store_settings, public.wishlist_items, public.profiles cascade;

-- Old signup triggers on auth.users (only ones calling functions in "public") wrote into the
-- old profiles table. If dropping the trigger isn't permitted, drop its function instead.
do $$
declare t record;
begin
  for t in
    select tg.tgname, p.oid::regprocedure as fn
    from pg_trigger tg
    join pg_proc p on p.oid = tg.tgfoid
    join pg_namespace n on n.oid = p.pronamespace
    where tg.tgrelid = 'auth.users'::regclass and not tg.tgisinternal and n.nspname = 'public'
  loop
    begin
      execute format('drop trigger if exists %I on auth.users', t.tgname);
    exception when insufficient_privilege then
      execute format('drop function if exists %s cascade', t.fn);
    end;
  end loop;
end $$;

drop function if exists public.place_order(jsonb) cascade;
drop function if exists public.admin_delete_user(uuid) cascade;
drop function if exists public.protect_profile() cascade;
drop function if exists public.protect_role() cascade;
drop function if exists public.handle_new_user() cascade;
drop function if exists public.is_admin() cascade;
drop type if exists public.app_role cascade;

-- Storage policies for the app buckets are recreated below (skipped with a notice if not permitted).
do $$
declare p record;
begin
  for p in
    select policyname from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and (coalesce(qual, '') || coalesce(with_check, '')) ~ '(product-images|payment-proofs)'
  loop
    begin
      execute format('drop policy if exists %I on storage.objects', p.policyname);
    exception when insufficient_privilege then
      raise notice 'Could not drop storage policy "%" (not permitted) — left as is.', p.policyname;
    end;
  end loop;
end $$;

-- Existing buckets keep their files but get the right visibility and limits.
do $$
begin
  update storage.buckets set public = true where id = 'product-images';
  update storage.buckets
    set public = false, file_size_limit = 5242880, allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp']
    where id = 'payment-proofs';
exception when insufficient_privilege then
  raise notice 'Could not update storage buckets (not permitted).';
end $$;

-- 3. App schema (copied from supabase/migrations/20261019000000_ecommerce.sql).
${appSchema}

-- 4. Recreate profiles for every existing auth user, keeping admin roles.
insert into public.profiles (id, email, name, phone, role, created_at)
select
  u.id,
  coalesce(u.email, ''),
  coalesce(nullif(o.full_name, ''), u.raw_user_meta_data ->> 'name', u.raw_user_meta_data ->> 'full_name', ''),
  coalesce(u.raw_user_meta_data ->> 'phone', ''),
  case when o.role = 'admin' then 'admin'::public.app_role else 'user'::public.app_role end,
  u.created_at
from auth.users u
left join _old_profiles o on o.id = u.id
on conflict (id) do nothing;

-- 5. Starter products (copied from supabase/seed.sql).
${seed}

commit;

-- Check: should list your accounts with their roles.
select email, name, role from public.profiles order by created_at;
`

mkdirSync(new URL('../supabase/repair/', import.meta.url), { recursive: true })
writeFileSync(new URL('../supabase/repair/reset_to_app_schema.sql', import.meta.url), sql)
console.log('Wrote supabase/repair/reset_to_app_schema.sql')
